// Static build: src/pages/**.html  ->  docs/**.html (served by GitHub Pages)
// - wraps each page in its layout (front matter between --- lines, JSON)
// - inlines {{icon:name extra-class}} as SVG, resolves {{root}}
// - adds width/height to <img> tags from the WebP headers
// - fails on unknown icons, missing files and broken internal links / anchors
import fs from 'node:fs';
import path from 'node:path';
import { ICONS } from './src/icons.mjs';
import { layout } from './src/layouts.mjs';

const SRC = 'src';
const OUT = 'docs';
const errors = [];

const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : [p];
});
const posix = p => p.split(path.sep).join('/');

function copyDir(from, to) {
  for (const f of walk(from)) {
    const dest = path.join(to, path.relative(from, f));
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(f, dest);
  }
}

function svg(name, cls = '') {
  if (!ICONS[name]) { errors.push(`unknown icon "${name}"`); return ''; }
  return `<svg class="ic${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${ICONS[name]}</svg>`;
}

function webpSize(file) {
  const b = fs.readFileSync(file);
  const kind = b.toString('ascii', 12, 16);
  if (kind === 'VP8X') return [1 + b.readUIntLE(24, 3), 1 + b.readUIntLE(27, 3)];
  if (kind === 'VP8 ') return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  if (kind === 'VP8L') {
    const bits = b.readUInt32LE(21);
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1];
  }
  return null;
}

fs.rmSync(OUT, { recursive: true, force: true });
copyDir(path.join(SRC, 'assets'), path.join(OUT, 'assets'));
fs.writeFileSync(path.join(OUT, 'assets/js/icons.js'),
  `/* generated by build.mjs */\nwindow.BX_ICONS=${JSON.stringify(ICONS)};\n`);
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');

const pages = walk(path.join(SRC, 'pages')).filter(f => f.endsWith('.html'));
const built = new Map();

for (const file of pages) {
  const rel = posix(path.relative(path.join(SRC, 'pages'), file));
  const depth = rel.split('/').length - 1;
  const root = depth ? '../'.repeat(depth) : '';
  let raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  let meta = {};
  if (raw.startsWith('---\n')) {
    const end = raw.indexOf('\n---\n', 4);
    try { meta = JSON.parse(raw.slice(4, end)); } catch (e) { errors.push(`${rel}: bad front matter (${e.message})`); }
    raw = raw.slice(end + 5);
  }
  meta.path = rel;
  let html = layout(meta, raw)
    .replace(/\{\{root\}\}/g, root)
    .replace(/\{\{icon:([a-z0-9-]+)(?: ([^}]+))?\}\}/g, (_, n, cls) => svg(n, cls));
  const left = html.match(/\{\{[^}]*\}\}/);
  if (left) errors.push(`${rel}: unresolved placeholder ${left[0]}`);

  html = html.replace(/<img\b([^>]*?)\bsrc="([^"]+\.webp)"([^>]*)>/g, (tag, a, src, b) => {
    if (/\bwidth=/.test(a + b)) return tag;
    const f = path.join(OUT, path.dirname(rel), src);
    if (!fs.existsSync(f)) return tag; // reported by the link check
    const size = webpSize(f);
    return size ? `<img${a}src="${src}" width="${size[0] / 2}" height="${size[1] / 2}"${b}>` : tag;
  });

  const dest = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, html);
  built.set(rel, html);
}

// ---- link + asset check ----
const idsOf = html => new Set([...html.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]));
for (const [rel, html] of built) {
  const refs = [...html.matchAll(/\s(?:href|src)="([^"]+)"/g)].map(m => m[1]);
  for (const ref of refs) {
    if (/^(https?:|mailto:|tel:|data:|javascript:)/.test(ref) || ref.includes("'")) continue; // external, or built inside an inline script
    const [pq, hash] = ref.split('#');
    const p = pq.split('?')[0];
    const target = p ? posix(path.normalize(path.join(path.dirname(rel), p))) : rel;
    if (p && !fs.existsSync(path.join(OUT, target))) { errors.push(`${rel}: missing ${ref}`); continue; }
    if (hash && target.endsWith('.html')) {
      const h = built.get(target);
      if (h && !idsOf(h).has(hash)) errors.push(`${rel}: missing anchor ${ref}`);
    }
  }
  const dup = [...html.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]).filter((v, i, a) => a.indexOf(v) !== i);
  if (dup.length) errors.push(`${rel}: duplicate ids ${[...new Set(dup)].join(', ')}`);
}
// assets referenced from CSS / JS
for (const f of walk(path.join(OUT, 'assets')).filter(f => /\.(css|js)$/.test(f))) {
  const txt = fs.readFileSync(f, 'utf8');
  for (const m of txt.matchAll(/assets\/img\/([\w-]+\.(?:webp|svg|png))/g)) {
    if (!fs.existsSync(path.join(OUT, 'assets/img', m[1]))) errors.push(`${posix(f)}: missing image ${m[1]}`);
  }
}

if (errors.length) {
  console.error(`Build finished with ${errors.length} problem(s):\n - ` + errors.join('\n - '));
  process.exit(1);
}
console.log(`Built ${built.size} pages into ${OUT}/ – no broken links.`);
